"""Generate Docs/Parameters.md from Source/Core/Params.h (single source of truth)."""
import re, pathlib

root = pathlib.Path(__file__).resolve().parents[1]
src = (root / "Source/Core/Params.h").read_text(encoding="utf-8")
row = re.compile(r'^X\((\w+),\s*"([^"]+)",\s*"([^"]+)",\s*(\w),\s*([-\d.f]+),\s*([-\d.f]+),\s*([-\d.f]+),\s*(\d),'
                 r'\s*"([^"]*)",\s*"([^"]*)",\s*"((?:[^"\\]|\\.)*)"\)', re.M)
section = re.compile(r'^/\* --- (.+?) --- \*/', re.M)
events = sorted([(m.start(), 's', m) for m in section.finditer(src)] + [(m.start(), 'r', m) for m in row.finditer(src)],
                key=lambda e: e[0])
kinds = {"F": "float", "B": "on/off", "C": "choice", "I": "integer"}
out = ["# Parameter reference", "",
       "Generated by `tools/gen_param_doc.py` from `Source/Core/Params.h`. IDs are stable host automation IDs.", ""]


def num(s):
    return s.rstrip('f')


for _, t, m in events:
    if t == 's':
        out += ["", f"## {m.group(1)[0].upper() + m.group(1)[1:]}", "",
                "| ID | Name | Type | Range | Default | Description |", "|---|---|---|---|---|---|"]
        continue
    e, pid, name, k, lo, hi, df, skew, unit, choices, tip = m.groups()
    if k == "C":
        opts = choices.split("|")
        rng = " / ".join(opts)
        dflt = opts[int(float(num(df)))]
    elif k == "B":
        rng, dflt = "off / on", ("on" if float(num(df)) > 0.5 else "off")
    elif unit == "%":
        rng = f"{float(num(lo)) * 100:g}–{float(num(hi)) * 100:g} %"
        dflt = f"{float(num(df)) * 100:g} %"
    else:
        u = f" {unit}" if unit else ""
        rng = f"{num(lo)}–{num(hi)}{u}" + (" (log)" if skew == "1" else "")
        dflt = f"{num(df)}{u}"
    out.append(f"| `{pid}` | {name} | {kinds[k]} | {rng} | {dflt} | {tip.replace('|', '/')} |")

n = sum(1 for e in events if e[1] == 'r')
out += ["", f"Total: {n} parameters.", ""]
(root / "Docs/Parameters.md").write_text("\n".join(out), encoding="utf-8")
print(n)
